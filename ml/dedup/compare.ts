// End-to-end comparison on the same data: dedup rule vs trained classifier, scored against the answer key.
// Writes ml/dedup/RESULTS.md.
//   node sim/gen.ts --loads 3000 --users 100 --hours 2 --seed 1 --out out-eval
//   node ml/dedup/compare.ts --data out-eval
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../..');
const { values: a } = parseArgs({ options: { data: { type: 'string', default: 'out-eval' }, speed: { type: 'string', default: '60' }, minutes: { type: 'string', default: '1.5' } } });
const modelFile = join(here, 'model.json');

const run = (extra: string[]) => {
  const r = spawnSync(process.execPath, [join(root, 'scripts/run.ts'), '--data', a.data!, '--speed', a.speed!, '--minutes', a.minutes!, '--port-base', '17101', '--metrics-port', '19465', ...extra], { encoding: 'utf8' });
  if (r.status !== 0) throw new Error(r.stderr);
  return JSON.parse(r.stdout.split('\n').find((l) => l.startsWith('RUN_RESULT '))!.slice(11));
};
const rule = run([]);
const model = run(['--dedup-model', modelFile]);
const m = JSON.parse(readFileSync(modelFile, 'utf8'));
const pct = (x: number) => `${(100 * x).toFixed(2)}%`;
const row = (name: string, r: any) => `| ${name} | ${r.score.expected} | ${r.score.delivered} | ${pct(r.score.missRate)} (${r.score.missedOpen5Min} open 5+ min) | ${r.score.duplicates} (${pct(r.score.duplicateRate)}) | ${r.score.unexpected} | ${r.score.latencySec.p50.toFixed(1)} / ${r.score.latencySec.p95.toFixed(1)} s |`;
const off = (x: any) => `| ${x.model} | ${x.precision} | ${x.recall} | ${x.wrong_merges} | ${x.missed_merges} | ${x.pr_auc ?? '—'} |`;

writeFileSync(join(here, 'RESULTS.md'), `# Dedup classifier: results

Generated by \`node ml/dedup/compare.ts --data ${a.data}\` on ${new Date().toISOString().slice(0, 10)}. Background and method: [ML.md](../../ML.md).

## Offline (held-out pairs, split by time)

Training data: ${m.data.pairs} candidate pairs (${m.data.positives} same-load) from \`sim/gen.ts --seed 11\`; test = the last 20% by time
(${m.data.test} pairs). Threshold chosen for precision ≥ ${m.data.target_precision} on the validation split (logistic ${m.thresholds.logistic.toFixed(3)}, LightGBM ${m.thresholds.lightgbm.toFixed(3)}).

| Model | Precision | Recall | Wrong merges (hidden loads) | Missed merges (duplicates) | PR-AUC |
| --- | --- | --- | --- | --- | --- |
${m.metrics.map(off).join('\n')}

The engine ships the logistic model (${m.features.length} weights, pure TypeScript, parity with Python checked on load). LightGBM is listed for comparison.

## End to end (same data and settings, scored against the answer key)

Data: \`${a.data}\` (seed 1, never seen in training), ${a.minutes} real minutes at ${a.speed}× speed.

| Dedup | Expected alerts | Delivered | Missed | Duplicates | Unexpected | p50 / p95 latency |
| --- | --- | --- | --- | --- | --- | --- |
${row('rule', rule)}
${row('classifier', model)}
`);
console.log(JSON.stringify({ rule: rule.score, classifier: model.score }));
